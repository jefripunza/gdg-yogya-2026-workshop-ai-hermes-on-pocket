#!/usr/bin/env bash
# ==============================================================================
# hc.sh - Hermes Configuration Updater (9Router Integration)
# Penggunaan: ./hc.sh <combo-name> <api-key>
# Contoh    : ./hc.sh gdg-yogya 9r-xxxxxxxxxxxxxx
# ==============================================================================

set -e

# Versi Script
HC_SH_VERSION="v2.3.0"

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

echo -e "${BLUE}================================================================${NC}"
echo -e "${GREEN}   Hermes Config Updater - 9Router Integration (${HC_SH_VERSION})    ${NC}"
echo -e "${BLUE}================================================================${NC}"

COMBO_NAME="$1"
API_KEY="$2"

# Input interaktif jika argumen belum lengkap
if [ -z "$COMBO_NAME" ]; then
    echo -e "${YELLOW}Nama Combo Model di 9Router (default: gdg-yogya):${NC}"
    read -r -p "> " INPUT_COMBO
    COMBO_NAME="${INPUT_COMBO:-gdg-yogya}"
fi

if [ -z "$API_KEY" ]; then
    echo -e "${YELLOW}Masukkan API Key 9Router Anda (dibuat di dashboard 9Router):${NC}"
    read -r -p "> " API_KEY
fi

if [ -z "$API_KEY" ]; then
    echo -e "${RED}[ERROR] API Key tidak boleh kosong!${NC}"
    echo "Penggunaan: ./hc.sh <combo-name> <api-key>"
    exit 1
fi

HERMES_DIR="${HERMES_HOME:-$HOME/.hermes}"
mkdir -p "$HERMES_DIR"
mkdir -p "$HERMES_DIR/logs"

CONFIG_FILE="$HERMES_DIR/config.yaml"
ENV_FILE="$HERMES_DIR/.env"

# Auto-detect proxy URL (Docker Compose service '9router' vs Localhost Termux)
PROXY_URL="${PROXY_URL:-}"
if [ -z "$PROXY_URL" ]; then
    if grep -q "9router" /etc/hosts 2>/dev/null || ping -c 1 -W 1 9router >/dev/null 2>&1 || getent hosts 9router >/dev/null 2>&1; then
        PROXY_URL="http://9router:20128/v1"
    else
        PROXY_URL="http://127.0.0.1:20128/v1"
    fi
fi

echo -e "\n${BLUE}[1/3] Menulis konfigurasi Hermes ke ${CONFIG_FILE}...${NC}"

# Backup config lama jika ada
if [ -f "$CONFIG_FILE" ]; then
    cp "$CONFIG_FILE" "${CONFIG_FILE}.bak"
fi

# Tulis config.yaml dengan model custom pointing ke 9Router
cat << EOF > "$CONFIG_FILE"
# Hermes Agent Configuration (Auto-generated by hc.sh)
model:
  provider: custom
  default: "${COMBO_NAME}"
  base_url: "${PROXY_URL}"
  api_key: "${API_KEY}"
  api_mode: openai

platforms:
  telegram:
    enabled: true

# Logging & Terminal
terminal:
  color: true
EOF

echo -e "${GREEN}✓ config.yaml berhasil diperbarui.${NC}"

echo -e "\n${BLUE}[2/3] Menyimpan kredensial ke ${ENV_FILE}...${NC}"

# Buat atau perbarui variabel di .env
touch "$ENV_FILE"
# Hapus key lama jika sudah ada
sed -i '/^OPENAI_BASE_URL=/d' "$ENV_FILE" 2>/dev/null || true
sed -i '/^OPENAI_API_KEY=/d' "$ENV_FILE" 2>/dev/null || true
sed -i '/^CUSTOM_API_KEY=/d' "$ENV_FILE" 2>/dev/null || true

cat << EOF >> "$ENV_FILE"
OPENAI_BASE_URL=${PROXY_URL}
OPENAI_API_KEY=${API_KEY}
CUSTOM_API_KEY=${API_KEY}
HERMES_DASHBOARD_BASIC_AUTH_USERNAME=admin
HERMES_DASHBOARD_BASIC_AUTH_PASSWORD=123456
EOF

echo -e "${GREEN}✓ File .env berhasil diperbarui.${NC}"

echo -e "\n${BLUE}[3/3] Memperbarui status Hermes Gateway & Dashboard...${NC}"

# Pastikan TMPDIR valid di Termux
export TMPDIR="${PREFIX:-/data/data/com.termux/files/usr}/tmp"
mkdir -p "$TMPDIR"

# ------------------------------------------------------------------------------
# Universal Fix untuk Node.js di Android 15 (Bionic Linker & esbuild hook)
# ------------------------------------------------------------------------------
PREFIX_PATH="${PREFIX:-/data/data/com.termux/files/usr}"
FIX_FILE="$PREFIX_PATH/lib/node_android_fix.cjs"
mkdir -p "$PREFIX_PATH/lib"

cat << 'EOF' > "$FIX_FILE"
const nodeBin = process.env.PREFIX ? (process.env.PREFIX + '/bin/node') : '/data/data/com.termux/files/usr/bin/node';

// 1. Override process.execPath agar tidak menunjuk ke linker64 di Android 15
if (process.execPath && process.execPath.includes('linker')) {
  try {
    Object.defineProperty(process, 'execPath', {
      value: nodeBin,
      writable: false,
      configurable: true,
      enumerable: true
    });
  } catch (e) {}
}

// 2. Intercept child_process (execFileSync, spawnSync, spawn)
try {
  const cp = require('node:child_process');

  const patchCall = (file, args) => {
    if (typeof file === 'string') {
      if (file.includes('linker')) {
        return [nodeBin, args];
      }
      if (file.includes('esbuild/bin/esbuild') || file.endsWith('npm-cli.js')) {
        return [nodeBin, [file, ...(args || [])]];
      }
    }
    return [file, args];
  };

  const origExecFileSync = cp.execFileSync;
  cp.execFileSync = function (file, args, ...rest) {
    const [pfile, pargs] = patchCall(file, args);
    return origExecFileSync.call(this, pfile, pargs, ...rest);
  };

  const origSpawnSync = cp.spawnSync;
  cp.spawnSync = function (file, args, ...rest) {
    const [pfile, pargs] = patchCall(file, args);
    return origSpawnSync.call(this, pfile, pargs, ...rest);
  };

  const origSpawn = cp.spawn;
  cp.spawn = function (file, args, ...rest) {
    const [pfile, pargs] = patchCall(file, args);
    return origSpawn.call(this, pfile, pargs, ...rest);
  };
} catch (e) {}
EOF

export NODE_OPTIONS="--require $FIX_FILE"
unset ESBUILD_BINARY_PATH 2>/dev/null || true

# Perbaiki shebang script internal Hermes (khususnya npm-cli.js & node-deps.mjs)
# agar tidak memicu error Android linker64 (ELF executable too small)
HERMES_LIB="${PREFIX:-/data/data/com.termux/files/usr}/lib/hermes-agent"
if [ -d "$HERMES_LIB" ] && command -v termux-fix-shebang >/dev/null 2>&1; then
    echo -e "${BLUE}Menyelaraskan shebang internal Hermes tools (npm/node/scripts)...${NC}"
    find "$HERMES_LIB" -type f \( -name "*.js" -o -name "*.mjs" -o -name "*.sh" -o -name "npm" -o -name "npx" \) -exec termux-fix-shebang {} + 2>/dev/null || true
fi

# Patch node-deps.mjs: Menyelaraskan resolusi Node agar tidak merujuk ke linker64 di Android 15
NODE_DEPS="$HERMES_LIB/app/scripts/build/node-deps.mjs"
if [ -f "$NODE_DEPS" ] && command -v node >/dev/null 2>&1; then
    node -e "
    const fs = require('fs');
    const file = process.argv[1];
    if (fs.existsSync(file)) {
      let content = fs.readFileSync(file, 'utf8');
      if (content.includes('return [process.execPath, cli]')) {
        const replacement = 'const nodeExec = (process.execPath && !process.execPath.includes(\"linker\")) ? process.execPath : (process.env.PREFIX ? process.env.PREFIX + \"/bin/node\" : \"/data/data/com.termux/files/usr/bin/node\"); return [nodeExec, cli]';
        content = content.replace('return [process.execPath, cli]', replacement);
        fs.writeFileSync(file, content);
        console.log('✓ node-deps.mjs berhasil diselaraskan dengan Android Bionic Node');
      }
    }
    " "$NODE_DEPS" 2>/dev/null || true
fi

# Restart atau jalankan Hermes Gateway
if pgrep -f "hermes.*gateway" >/dev/null 2>&1; then
    echo -e "${YELLOW}Merestart Hermes Gateway...${NC}"
    pkill -f "hermes.*gateway" || true
    sleep 1
fi
nohup hermes gateway > "$HERMES_DIR/logs/gateway.log" 2>&1 &

# Tentukan flags hermes dashboard
WEB_DIST="$HERMES_LIB/app/hermes_cli/web_dist"
DASHBOARD_FLAGS="--host 127.0.0.1 --port 9118 --no-open"
if [ -d "$WEB_DIST" ]; then
    DASHBOARD_FLAGS="$DASHBOARD_FLAGS --skip-build"
fi

# Restart atau jalankan Hermes Dashboard & Relay
echo -e "${YELLOW}Merestart Hermes Dashboard & Relay...${NC}"
pkill -f "hermes.*dashboard" || true
pkill -f "socat.*9119" || true
sleep 1

if command -v socat >/dev/null 2>&1; then
    # Jalankan socat relay terlebih dahulu agar port 9119 langsung siap begitu 9118 hidup
    nohup socat TCP-LISTEN:9119,fork,reuseaddr,bind=0.0.0.0 TCP:127.0.0.1:9118 >/dev/null 2>&1 &

    NODE_OPTIONS="--require $FIX_FILE" nohup hermes dashboard $DASHBOARD_FLAGS > "$HERMES_DIR/logs/dashboard.log" 2>&1 &
    echo -n "Menunggu Hermes Web UI siap di port :9118"
    DASHBOARD_READY=false
    for i in $(seq 1 90); do
        if netstat -tlpn 2>/dev/null | grep -q "9118" || curl -sI "http://127.0.0.1:9118" 2>/dev/null | grep -q "HTTP"; then
            DASHBOARD_READY=true
            echo -e " ${GREEN}[SIAP!]${NC}"
            break
        fi
        if ! pgrep -f "hermes.*dashboard" >/dev/null 2>&1; then
            echo -e "\n${RED}[!] Hermes Dashboard berhenti.${NC}"
            break
        fi
        # Tampilkan status jika sedang kompilasi web UI
        if [ "$i" -eq 15 ] || [ "$i" -eq 40 ] || [ "$i" -eq 65 ]; then
            if grep -q "Building the web UI" "$HERMES_DIR/logs/dashboard.log" 2>/dev/null; then
                echo -n " [Kompilasi Web UI...]"
            fi
        fi
        echo -n "."
        sleep 1
    done

    if [ "$DASHBOARD_READY" = true ]; then
        echo -e "${GREEN}✓ Hermes Web Dashboard berhasil terhubung ke relay :9119${NC}"
    else
        echo -e "\n${YELLOW}Log Terakhir Hermes Dashboard (~/.hermes/logs/dashboard.log):${NC}"
        tail -n 20 "$HERMES_DIR/logs/dashboard.log" 2>/dev/null || true
    fi
else
    # Jika tidak ada socat (misal Docker container biasa), bind langsung ke 0.0.0.0:9119
    DASHBOARD_FLAGS_NO_SOCAT="--host 0.0.0.0 --port 9119 --no-open"
    if [ -d "$WEB_DIST" ]; then
        DASHBOARD_FLAGS_NO_SOCAT="$DASHBOARD_FLAGS_NO_SOCAT --skip-build"
    fi
    NODE_OPTIONS="--require $FIX_FILE" nohup hermes dashboard $DASHBOARD_FLAGS_NO_SOCAT > "$HERMES_DIR/logs/dashboard.log" 2>&1 &
    sleep 2
fi

PID_GW=$(pgrep -f "hermes.*gateway" | head -n 1 || true)
PID_HD=$(pgrep -f "hermes.*dashboard" | head -n 1 || true)

if pgrep -f "socat.*9119" >/dev/null 2>&1 || ( [ -n "$PID_HD" ] && ! command -v socat >/dev/null 2>&1 ); then
    echo -e "${GREEN}✓ Hermes Web Dashboard aktif -> http://localhost:9119${NC}"
else
    echo -e "${YELLOW}[INFO] Jika dashboard masih dalam proses build, tunggu sebentar lalu refresh http://localhost:9119${NC}"
fi

echo -e "\n${BLUE}================================================================${NC}"
echo -e "${GREEN}✓ Konfigurasi Hermes Berhasil Diterapkan!${NC}"
echo -e "${BLUE}================================================================${NC}"
echo -e "🔹 Combo Model : ${YELLOW}${COMBO_NAME}${NC}"
echo -e "🔹 Local Proxy : ${YELLOW}${PROXY_URL}${NC} (9Router)"
echo -e "🔹 Gateway PID : ${YELLOW}${PID_GW:-Aktif}${NC}"
echo -e ""
echo -e "Langkah Selanjutnya:"
echo -e "  1. Buka browser di HP/Laptop ke:"
echo -e "     ${GREEN}http://localhost:9119${NC} (Hermes Web Dashboard)"
echo -e "  2. Coba test chat dengan asisten Hermes Anda!"
echo -e "  3. Setelah itu, sambungkan ke Telegram menggunakan script:"
echo -e "     ${YELLOW}./ht.sh <token-telegram>${NC}"
echo -e "${BLUE}================================================================${NC}\n"

