#!/data/data/com.termux/files/usr/bin/bash
# ==============================================================================
# hc.sh - Hermes Configuration Updater (9Router Integration)
# Penggunaan: ./hc.sh <combo-name> <api-key>
# Contoh    : ./hc.sh gdg-yogya 9r-xxxxxxxxxxxxxx
# ==============================================================================

set -e

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

echo -e "${BLUE}================================================================${NC}"
echo -e "${GREEN}       Hermes Config Updater - 9Router Integration              ${NC}"
echo -e "${BLUE}================================================================${NC}"

COMBO_NAME="$1"
API_KEY="$2"

# Input interaktif jika argumen belum lengkap
if [ -z "$COMBO_NAME" ]; then
    echo -e "${YELLOW}Nama Combo Model di 9Router (default: gdg-yogya):${NC}"
    read -r -p "> " INPUT_COMBO
    COMBO_NAME="${INPUT_COMBO:-gdg-yogya}"
fi

if [ -z "$API_KEY" ]; then
    echo -e "${YELLOW}Masukkan API Key 9Router Anda (dibuat di dashboard 9Router):${NC}"
    read -r -p "> " API_KEY
fi

if [ -z "$API_KEY" ]; then
    echo -e "${RED}[ERROR] API Key tidak boleh kosong!${NC}"
    echo "Penggunaan: ./hc.sh <combo-name> <api-key>"
    exit 1
fi

HERMES_DIR="$HOME/.hermes"
mkdir -p "$HERMES_DIR"
mkdir -p "$HERMES_DIR/logs"

CONFIG_FILE="$HERMES_DIR/config.yaml"
ENV_FILE="$HERMES_DIR/.env"
PROXY_URL="http://127.0.0.1:20128/v1"

echo -e "\n${BLUE}[1/3] Menulis konfigurasi Hermes ke ~/.hermes/config.yaml...${NC}"

# Backup config lama jika ada
if [ -f "$CONFIG_FILE" ]; then
    cp "$CONFIG_FILE" "${CONFIG_FILE}.bak"
fi

# Tulis config.yaml dengan model custom pointing ke 9Router
cat << EOF > "$CONFIG_FILE"
# Hermes Agent Configuration (Auto-generated by hc.sh)
model:
  provider: custom
  default: "${COMBO_NAME}"
  base_url: "${PROXY_URL}"
  api_key: "${API_KEY}"
  api_mode: openai

platforms:
  telegram:
    enabled: true

# Logging & Terminal
terminal:
  color: true
EOF

echo -e "${GREEN}✓ config.yaml berhasil diperbarui.${NC}"

echo -e "\n${BLUE}[2/3] Menyimpan kredensial ke ~/.hermes/.env...${NC}"

# Buat atau perbarui variabel di ~/.hermes/.env
touch "$ENV_FILE"
# Hapus key lama jika sudah ada
sed -i '/^OPENAI_BASE_URL=/d' "$ENV_FILE" 2>/dev/null || true
sed -i '/^OPENAI_API_KEY=/d' "$ENV_FILE" 2>/dev/null || true
sed -i '/^CUSTOM_API_KEY=/d' "$ENV_FILE" 2>/dev/null || true

cat << EOF >> "$ENV_FILE"
OPENAI_BASE_URL=${PROXY_URL}
OPENAI_API_KEY=${API_KEY}
CUSTOM_API_KEY=${API_KEY}
EOF

echo -e "${GREEN}✓ File ~/.hermes/.env berhasil diperbarui.${NC}"

echo -e "\n${BLUE}[3/3] Memperbarui status Hermes Gateway...${NC}"

# Restart Hermes Gateway jika sedang berjalan agar config baru langsung aktif
if pgrep -f "hermes.*gateway" >/dev/null 2>&1; then
    echo -e "${YELLOW}Merestart Hermes Gateway...${NC}"
    pkill -f "hermes.*gateway" || true
    sleep 1
fi

nohup hermes gateway > "$HERMES_DIR/logs/gateway.log" 2>&1 &
sleep 1

PID_GW=$(pgrep -f "hermes.*gateway" | head -n 1 || true)

echo -e "\n${BLUE}================================================================${NC}"
echo -e "${GREEN}✓ Konfigurasi Hermes Berhasil Diterapkan!${NC}"
echo -e "${BLUE}================================================================${NC}"
echo -e "🔹 Combo Model : ${YELLOW}${COMBO_NAME}${NC}"
echo -e "🔹 Local Proxy : ${YELLOW}${PROXY_URL}${NC} (9Router)"
echo -e "🔹 Gateway PID : ${YELLOW}${PID_GW:-Aktif}${NC}"
echo -e ""
echo -e "Langkah Selanjutnya:"
echo -e "  1. Buka browser di HP/Laptop ke:"
echo -e "     ${GREEN}http://localhost:9119${NC} (Hermes Web Dashboard)"
echo -e "  2. Coba test chat dengan asisten Hermes Anda!"
echo -e "  3. Setelah itu, sambungkan ke Telegram menggunakan script:"
echo -e "     ${YELLOW}./ht.sh <token-telegram>${NC}"
echo -e "${BLUE}================================================================${NC}\n"

